import assert from "node:assert/strict";
import { test } from "node:test";
import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { chromium, type Browser, type Page } from "playwright-core";
import { createTestServer } from "./helpers/next-server";
import type { Run } from "../src/lib/topics/types";

test("topics browser: private proposal, confirmation, SSE reconnect, hierarchy, edit, routing and permissions", { timeout: 120_000 }, async t => {
  const app = await createTestServer();
  const resources: { browser?: Browser; page?: Page } = {};
  t.after(async () => {
    if (resources.page) { await writeFile("/tmp/xi-topics-browser.html", await resources.page.content()); await resources.page.screenshot({ path: "/tmp/xi-topics-browser.png", fullPage: true }); }
    await resources.browser?.close(); await app.dispose();
  });
  await app.migrate(); await app.start();
  const browser = resources.browser = await chromium.launch({ executablePath: process.env.XI_E2E_CHROME ?? "/usr/bin/google-chrome-stable", headless: true });
  const context = await browser.newContext();
  const page = resources.page = await context.newPage();
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  page.setDefaultTimeout(12_000);
  const signup = await context.request.post(`${app.origin}/api/auth/sign-up/email`, { headers: { Origin: app.origin }, data: { name: "Topic Editor", email: "topics@example.com", password: "topics browser password" } });
  assert.equal(signup.status(), 200);
  await page.goto(`${app.origin}/dashboard/topics`);
  await page.getByRole("heading", { name: "Gestion des topics", exact: true }).waitFor();
  await page.getByLabel("Intention privée", { exact: true }).fill("Politique mondiale, intention personnelle");
  await page.getByRole("button", { name: "Analyser et proposer" }).click();
  await page.getByLabel("Nom public", { exact: true }).fill("Politique");
  await page.getByLabel("Tag hiérarchique", { exact: true }).fill("politiks");
  await page.getByLabel("Scope public", { exact: false }).fill("La politique mondiale");
  assert.equal((await readdir(join(app.vaultPath, "topics"))).filter(f => f.endsWith(".md")).length, 0);
  await page.getByLabel("Je confirme le contenu public", { exact: false }).check();
  await page.getByRole("button", { name: "Confirmer la création" }).focus();
  await page.keyboard.press("Enter");
  await page.getByRole("button", { name: "Ouvrir la fiche du topic" }).waitFor();
  const runId = new URL(page.url()).searchParams.get("run")!;
  const runResponse = await context.request.get(`${app.origin}/api/topics/runs/${runId}`);
  const run = (await runResponse.json()).run as Run;
  assert.equal(run.state, "completed");
  // Reconnect with a stale event cursor: receive complete current state, with stable log identities.
  const wire = await page.evaluate(async ({ runId }) => {
    const controller = new AbortController();
    const response = await fetch(`/api/topics/runs/${runId}/events`, { headers: { "Last-Event-ID": "obsolete:1" }, signal: controller.signal });
    const reader = response.body!.getReader();
    let text = "";
    while (!text.includes("event: pipeline")) { const next = await reader.read(); text += new TextDecoder().decode(next.value); }
    controller.abort(); return text;
  }, { runId });
  assert.ok(wire.includes(`id: ${run.id}:${run.events.length}:completed`));
  assert.equal(JSON.parse(wire.split("data: ")[1]).topicId, run.topicId);
  await page.getByRole("button", { name: "Ouvrir la fiche du topic" }).click();
  await page.getByRole("heading", { name: "Politique politiks", exact: true }).waitFor();
  await page.getByLabel("Intention privée", { exact: true }).fill("Politique française");
  await page.getByRole("button", { name: "Analyser et proposer" }).click();
  await page.getByLabel("Tag hiérarchique", { exact: true }).fill("politiks.france");
  assert.equal(await page.getByLabel("Parent principal", { exact: true }).inputValue(), run.topicId);
  await page.getByLabel("Je confirme le contenu public", { exact: false }).check();
  await page.getByRole("button", { name: "Confirmer la création" }).click();
  await page.getByRole("button", { name: "Ouvrir la fiche du topic" }).waitFor();
  await page.getByRole("button", { name: "Ouvrir la fiche du topic" }).click();
  await page.getByRole("button", { name: "Modifier", exact: true }).click();
  await page.getByLabel("Tag hiérarchique", { exact: true }).fill("politiks.francais");
  await page.getByLabel("Je valide le périmètre", { exact: false }).check();
  await page.getByRole("button", { name: "Enregistrer", exact: true }).click();
  await page.getByText("Anciens tags : politiks.france", { exact: true }).waitFor();
  await page.getByLabel("Demande", { exact: true }).fill("Politique française");
  await page.getByRole("button", { name: "Proposer un routage" }).click();
  await page.getByText(/Correspondance déterministe avec politiks.francais/).waitFor();
  await page.getByLabel("Topic principal responsable", { exact: true }).selectOption(run.topicId);
  await page.getByRole("button", { name: "Valider la correction humaine" }).click();
  await page.getByText("Responsabilité et contexte corrigés par l’utilisateur.", { exact: true }).waitFor();
  await page.reload();
  await page.getByRole("button", { name: "Ouvrir la fiche du topic" }).waitFor();
  const outsider = await browser.newContext();
  const anonymous = await outsider.request.get(`${app.origin}/api/topics`);
  assert.equal(anonymous.status(), 401);
  await outsider.request.post(`${app.origin}/api/auth/sign-up/email`, { headers: { Origin: app.origin }, data: { name: "Other", email: "other-topics@example.com", password: "topics browser password" } });
  assert.equal((await outsider.request.get(`${app.origin}/api/topics/runs/${runId}`)).status(), 404);
  assert.equal((await outsider.request.get(`${app.origin}/api/topics/runs/${runId}/events`)).status(), 404);
  assert.equal((await outsider.request.get(`${app.origin}/api/topics`)).status(), 200);
  assert.equal((await context.request.post(`${app.origin}/api/topics/runs`, { headers: { Origin: "https://foreign.example" }, data: { intent: "Cross origin" } })).status(), 403);
  const feed = await context.request.get(`${app.origin}/api/feed`);
  assert.ok(!(await feed.text()).includes("intention personnelle"));
  assert.deepEqual(await readdir(join(app.vaultPath, "posts")), []);
  assert.deepEqual(errors, []);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Ouvrir le menu", exact: true }).click();
  await page.getByRole("link", { name: "Gestion des topics", exact: true }).last().waitFor();
});

test("requested subject creates its missing parent explicitly before the child", { timeout: 120_000 }, async t => {
  const app = await createTestServer();
  const resources: { browser?: Browser } = {};
  t.after(async () => { await resources.browser?.close(); await app.dispose(); });
  await app.migrate(); await app.start();
  const browser = resources.browser = await chromium.launch({ executablePath: process.env.XI_E2E_CHROME ?? "/usr/bin/google-chrome-stable", headless: true });
  const context = await browser.newContext(); const page = await context.newPage(); page.setDefaultTimeout(12_000);
  await context.request.post(`${app.origin}/api/auth/sign-up/email`, { headers: { Origin: app.origin }, data: { name: "Subject Editor", email: "subjects@example.com", password: "subjects browser password" } });
  await page.goto(`${app.origin}/dashboard/topics`);
  await page.getByLabel("Intention privée", { exact: true }).fill("Je souhaite suivre la politique française");
  await page.getByRole("button", { name: "Analyser et proposer" }).click();
  await page.getByText("Parent manquant à confirmer", { exact: true }).waitFor();
  const childRunId = new URL(page.url()).searchParams.get("run");
  assert.equal((await (await context.request.get(`${app.origin}/api/topics`)).json()).topics.length, 0);
  await page.getByRole("button", { name: "Proposer le parent manquant" }).click();
  await page.getByLabel("Nom public", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("Tag hiérarchique", { exact: true }).inputValue(), "politiks");
  await page.getByLabel("Je confirme le contenu public", { exact: false }).check();
  await page.getByRole("button", { name: "Confirmer la création", exact: true }).click();
  await page.getByRole("button", { name: "Continuer vers le topic demandé" }).waitFor();
  await page.reload();
  await page.getByRole("button", { name: "Continuer vers le topic demandé" }).click();
  await page.getByLabel("Nom public", { exact: true }).waitFor();
  assert.equal(new URL(page.url()).searchParams.get("run"), childRunId);
  assert.equal(await page.getByLabel("Nom public", { exact: true }).inputValue(), "Politique française");
  assert.equal(await page.getByLabel("Tag hiérarchique", { exact: true }).inputValue(), "politiks.france");
  assert.equal(await page.getByLabel("Scope public", { exact: false }).inputValue(), "Politique, institutions et actualité politique françaises");
  assert.equal(await page.getByLabel("Je confirme le contenu public", { exact: false }).isChecked(), false);
  assert.equal((await (await context.request.get(`${app.origin}/api/topics`)).json()).topics.length, 1);
  await page.getByLabel("Je confirme le contenu public", { exact: false }).check();
  await page.getByRole("button", { name: "Confirmer la création", exact: true }).click();
  await page.getByRole("button", { name: "Ouvrir la fiche du topic" }).waitFor();
  const topics = (await (await context.request.get(`${app.origin}/api/topics`)).json()).topics;
  assert.equal(topics.length, 2);
  const child = topics.find((topic: { tag: string }) => topic.tag === "politiks.france");
  await page.goto(`${app.origin}/dashboard/accounts`);
  await page.getByLabel("Topic de départ").selectOption(child.id);
  await page.getByRole("button", { name: "Proposer un ΞAgent", exact: true }).click();
  await page.getByLabel("Nom du ΞAgent", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("Nom du ΞAgent", { exact: true }).inputValue(), "Politique française");
  assert.equal(await page.getByLabel("Handle public").inputValue(), "politiks.france");
});
