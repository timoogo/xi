import assert from "node:assert/strict";
import { test } from "node:test";
import { chromium } from "playwright-core";
import { createTestServer } from "./helpers/next-server";

test("accounts Chrome: proposal, reload, presets, confirmation, edits, isolation and mobile navigation", { timeout: 120_000 }, async t => {
  const app = await createTestServer(); t.after(() => app.dispose()); await app.migrate(); await app.start();
  const browser = await chromium.launch({ executablePath: process.env.XI_E2E_CHROME ?? "/usr/bin/google-chrome-stable", headless: true }); t.after(() => browser.close());
  const context = await browser.newContext(); const page = await context.newPage(); page.setDefaultTimeout(12_000);
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  assert.equal((await context.request.post(`${app.origin}/api/auth/sign-up/email`, { headers: { Origin: app.origin }, data: { name: "Editor", email: "accounts@example.com", password: "editorial test password" } })).status(), 200);
  const headers = { Origin: app.origin };
  const proposal = await (await context.request.post(`${app.origin}/api/topics/runs`, { headers, data: { intent: "La politique" } })).json();
  await context.request.post(`${app.origin}/api/topics/runs/${proposal.run.id}`, { headers, data: { action: "resume" } });
  const confirmed = await (await context.request.post(`${app.origin}/api/topics/runs/${proposal.run.id}`, { headers, data: { action: "confirm", relationsConfirmed: true, draft: { tag: "politiks", name: "Politique", description: "Actualité politique", scope: "La politique française", parentId: null, relatedIds: [] } } })).json();
  assert.equal(confirmed.run.state, "completed");
  await page.goto(`${app.origin}/dashboard/accounts`);
  await page.getByLabel("Topic de départ").selectOption(confirmed.run.topicId);
  await page.getByRole("button", { name: "Proposer un compte", exact: true }).click();
  await page.getByLabel("Nom du compte", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("Handle public").inputValue(), "politiks");
  await page.reload(); await page.getByLabel("Nom du compte", { exact: true }).waitFor();
  await page.getByLabel("Preset et version").selectOption("pedagogue:1");
  await page.getByLabel("Ton", { exact: true }).fill("Clair et précis");
  await page.getByLabel("Nom du preset personnalisé").fill("Clarté");
  await page.getByRole("button", { name: "Enregistrer comme nouveau preset" }).click();
  await page.getByText("Preset réutilisable enregistré.", { exact: true }).waitFor();
  await page.getByLabel("Je confirme le compte", { exact: false }).check();
  await page.getByRole("button", { name: "Confirmer la création", exact: true }).click();
  await page.getByText("État : Compte créé", { exact: true }).waitFor();
  const runId = new URL(page.url()).searchParams.get("run")!;
  const wire = await page.evaluate(async id => { const controller = new AbortController(); const response = await fetch(`/api/accounts/runs/${id}/events`, { headers: { "Last-Event-ID": "old" }, signal: controller.signal }); const reader = response.body!.getReader(); let text = ""; while (!text.includes("event: pipeline")) { const result = await reader.read(); text += new TextDecoder().decode(result.value); } controller.abort(); return text; }, runId);
  assert.ok(wire.includes('"state":"completed"'));
  await page.getByRole("button", { name: "Configurer @politiks", exact: true }).click();
  await page.getByLabel("Nom du compte", { exact: true }).fill("Politique expliquée");
  await page.getByLabel("Compte actif", { exact: true }).uncheck();
  await page.getByLabel("Ton", { exact: true }).fill("Clair et progressif");
  await page.getByRole("button", { name: "Créer une nouvelle version du preset" }).click();
  await page.getByText(/Nouvelle version créée/).waitFor();
  assert.match(await page.getByLabel("Preset et version").inputValue(), /:1$/);
  await page.getByLabel("Je confirme le compte", { exact: false }).check();
  await page.getByRole("button", { name: "Enregistrer le compte", exact: true }).click();
  await page.getByText("Compte enregistré.", { exact: true }).waitFor();
  await page.reload(); await page.getByText("Inactif · politiks · preset v1", { exact: true }).waitFor();
  const anonymous = await browser.newContext(); assert.equal((await anonymous.request.get(`${app.origin}/api/accounts`)).status(), 401);
  await anonymous.request.post(`${app.origin}/api/auth/sign-up/email`, { headers, data: { name: "Other", email: "other-accounts@example.com", password: "editorial test password" } });
  assert.equal((await anonymous.request.get(`${app.origin}/api/accounts/runs/${runId}`)).status(), 404);
  assert.equal((await anonymous.request.get(`${app.origin}/api/accounts/runs/${runId}/events`)).status(), 404);
  assert.equal((await context.request.post(`${app.origin}/api/accounts/runs`, { headers: { Origin: "https://foreign.example" }, data: { topicId: confirmed.run.topicId } })).status(), 403);
  await page.setViewportSize({ width: 390, height: 844 }); await page.getByRole("button", { name: "Ouvrir le menu", exact: true }).click(); await page.getByRole("link", { name: "Comptes éditoriaux", exact: true }).last().waitFor();
  assert.deepEqual(errors, []);
});
