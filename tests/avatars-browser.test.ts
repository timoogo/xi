import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { randomUUID } from "node:crypto";
import Database from "better-sqlite3";
import { chromium, type Browser } from "playwright-core";
import { createTestServer } from "./helpers/next-server";
import { diagnoseOnFailure } from "./helpers/diagnostics";
import { hydrated } from "./helpers/hydration";
import { createPublicationStore } from "../src/lib/publications/store";
import { openVault } from "../src/lib/publications/vault";

test("identités Bloub : profils, publications, agent, persistance et données historiques", { timeout: 120_000 }, async t => {
  const app = await createTestServer();
  const resources: { browser?: Browser } = {};
  diagnoseOnFailure(t, app, () => resources.browser);
  t.after(async () => { await resources.browser?.close(); await app.dispose(); });
  await app.migrate(); await app.start();
  const browser = resources.browser = await chromium.launch({ executablePath: process.env.XI_E2E_CHROME ?? "/usr/bin/google-chrome-stable", headless: true });
  const context = await browser.newContext();
  const headers = { Origin: app.origin };
  const registered = await context.request.post(`${app.origin}/api/auth/sign-up/email`, { headers, data: { name: "Alice", email: "alice@example.com", password: "avatar test password" } });
  assert.equal(registered.status(), 200);
  const user = (await registered.json()).user as { id: string };
  const db = new Database(app.databasePath);
  t.after(() => db.close());
  const preference = () => db.prepare("SELECT seed, mode, revision FROM user_avatar WHERE user_id=?").get(user.id) as { seed: string; mode: string; revision: number };
  const oldFile = join(dirname(app.databasePath), "avatars", "historical.webp");
  await mkdir(dirname(oldFile), { recursive: true });
  await writeFile(oldFile, "historical photo");
  db.prepare('UPDATE "user" SET image=? WHERE id=?').run("/api/avatars/historical.webp", user.id);
  const original = preference();
  assert.equal(original.mode, "photo");
  const page = await context.newPage();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${app.origin}/dashboard/settings`);
  const preview = page.getByLabel("Aperçu de l’avatar").locator("[data-bloub]");
  assert.equal(await preview.getAttribute("data-seed"), original.seed);
  await page.getByRole("img", { name: "Avatar Bloub de Alice" }).first().waitFor();
  assert.equal(await page.locator('input[type="file"]').count(), 0);
  assert.equal(await page.getByRole("button", { name: /photo/i }).count(), 0);
  await page.goto(`${app.origin}/dashboard/profile`);
  await page.locator(`main [data-seed="${original.seed}"]`).first().waitFor();
  await page.goto(`${app.origin}/dashboard/settings`);
  assert.equal((await context.request.put(`${app.origin}/api/account/avatar`, { headers, data: "photo" })).status(), 405);
  assert.equal((await context.request.delete(`${app.origin}/api/account/avatar`, { headers })).status(), 405);
  const patch = (data: unknown) => context.request.patch(`${app.origin}/api/account/avatar`, { headers, data });
  const anonymous = await browser.newContext();
  assert.equal((await anonymous.request.patch(`${app.origin}/api/account/avatar`, { headers, data: original })).status(), 401);
  await anonymous.close();
  assert.equal((await context.request.patch(`${app.origin}/api/account/avatar`, { headers: { Origin: "https://foreign.example" }, data: original })).status(), 403);
  assert.equal((await patch({ seed: "invalid", revision: original.revision })).status(), 400);
  assert.equal((await patch({ ...original, mode: "photo" })).status(), 400);
  await hydrated(page.getByRole("button", { name: "Régénérer" }));
  await page.getByRole("button", { name: "Régénérer" }).click();
  const chosen = await preview.getAttribute("data-seed");
  assert.notEqual(chosen, original.seed);
  assert.deepEqual(preference(), original);
  await page.getByRole("button", { name: "Enregistrer", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Avatar enregistré." }).waitFor();
  assert.equal(preference().seed, chosen);
  assert.equal((await patch({ seed: original.seed, revision: original.revision })).status(), 409);
  await page.reload();
  assert.equal(await preview.getAttribute("data-seed"), chosen);
  assert.equal(await readFile(oldFile, "utf8"), "historical photo");
  assert.equal((db.prepare('SELECT image FROM "user" WHERE id=?').get(user.id) as {image: string}).image, "/api/avatars/historical.webp");
  const localDb = new Database(":memory:");
  t.after(() => localDb.close());
  const store = createPublicationStore({ vault: await openVault(app.vaultPath), db: localDb });
  const id = await store.create(user);
  const draft = await store.getEditable(user, id);
  const saved = await store.save(user, id, { baseRevision: draft.revision, summary: "", visibility: "public", messages: [{ key: "one", file: null, body: "Publication avec Bloub" }] });
  assert.ok(saved.ok);
  await store.publish(user, id, saved.snapshot.revision);
  const agent = randomUUID();
  const agentPath = join(app.vaultPath, "generators", "agent-test");
  await mkdir(agentPath, { recursive: true });
  await writeFile(join(agentPath, "index.md"), `---\nid: ${agent}\nslug: agent-test\ntitle: Agent Test\nowner_id: ${user.id}\nvisibility: public\ncreated_at: 2026-10-20T12:00:00Z\neditorial:\n  active: true\n---\n`);
  // Wait for the server's vault index, as with an external Obsidian write.
  await page.waitForFunction(async id => (await fetch(`/api/publications/${id}`)).ok, id);
  for (const path of ["/dashboard", "/dashboard/profile", `/dashboard/profiles/${user.id}`, `/dashboard/publications/${id}`, `/dashboard/publications/${id}/conversation/1`]) {
    await page.goto(app.origin + path);
    await page.locator(`main [data-seed="${chosen}"]`).first().waitFor();
    assert.ok(await page.getByRole("img", { name: "Avatar Bloub de Alice" }).count() > 0);
  }
  await page.goto(`${app.origin}/dashboard/profiles/${agent}`);
  await page.getByRole("img", { name: "Avatar Bloub de Agent Test" }).first().waitFor();
  await app.stop(); await app.start();
  await page.goto(`${app.origin}/dashboard/settings`);
  assert.equal(await preview.getAttribute("data-seed"), chosen);
  assert.equal(await readFile(oldFile, "utf8"), "historical photo");
  assert.deepEqual(errors, []);
});
