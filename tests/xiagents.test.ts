import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { test } from "node:test";
import Database from "better-sqlite3";
import { openVault } from "../src/lib/publications/vault";
import { createPublicationStore } from "../src/lib/publications/store";
import { createAccountStore } from "../src/lib/accounts/store";
import { createTopicStore } from "../src/lib/topics/store";
import { createGraphRepository } from "../src/lib/graph/repository";
import { manualPublication } from "../src/lib/xiagents/manual-publication";
import { generateFixture } from "../src/lib/xiagents/generator";

test("ΞAgents: local preview, private publication, ownership, Markdown, threads, retries and rebuild", async t => {
  const root = await mkdtemp(join(tmpdir(), "xi-agent-"));
  const db = new Database(":memory:");
  t.after(async () => { db.close(); await rm(root, { recursive: true, force: true }); });
  const vault = await openVault(root);
  const topics = createTopicStore({ vault, db });
  const accounts = createAccountStore({ vault, db, topics });
  const publications = createPublicationStore({ vault, db });
  const run = await topics.propose("alice", "Un jardin fictif");
  await topics.confirm("alice", run.id, { tag: "politiks", name: "Politiks", description: "Test", scope: "Simulation fictive", parentId: null, relatedIds: [] }, true);
  const proposed = await accounts.propose("alice", run.topicId);
  const ready = await accounts.resume("alice", proposed.id);
  await accounts.confirm("alice", ready.id, ready.draft, true);
  const agent = await accounts.getOwned("alice", ready.accountId);
  await assert.rejects(accounts.getOwned("bob", agent.id), /introuvable/);
  const choice = { seed: randomUUID(), count: 4, accountRevision: agent.editorial!.revision };
  assert.deepEqual(generateFixture(choice), generateFixture(choice));
  assert.notDeepEqual(generateFixture(choice), generateFixture({ ...choice, seed: randomUUID() }));
  const call = (owner: string, data: unknown) => manualPublication(accounts, topics, publications, owner, agent.id, data);
  const preview = await call("alice", { ...choice, action: "generate" });
  assert.ok("preview" in preview);
  assert.equal(preview.preview!.messages.length, 4);
  assert.equal((await publications.page({ id: "alice" }, { kind: "home" })).items.length, 0);
  for (const data of [{ ...choice, action: "publish", confirmed: false }, { ...choice, action: "generate", count: 11 }, { ...choice, action: "publish", confirmed: true, visibility: "public" }, { ...choice, action: "generate", owner: "alice" }]) await assert.rejects(call("alice", data));
  await assert.rejects(call("bob", { ...choice, action: "publish", confirmed: true }), /introuvable/);
  await assert.rejects(call("alice", { ...choice, action: "publish", confirmed: true, accountRevision: randomUUID() }), /changé/);
  const saved = await call("alice", { ...choice, action: "publish", confirmed: true });
  assert.ok(saved.publication);
  assert.equal(saved.publication.authorId, agent.id); assert.equal(saved.publication.authorType, "ai");
  assert.equal(saved.publication.visibility, "private"); assert.equal(saved.publication.type, "thread");
  assert.deepEqual(saved.publication.messages.map(m => m.body), preview.preview!.messages);
  const [retry, concurrent] = await Promise.all([call("alice", { ...choice, action: "publish", confirmed: true }), call("alice", { ...choice, action: "publish", confirmed: true })]);
  assert.equal(concurrent.publication!.id, saved.publication.id);
  assert.equal(retry.publication!.id, saved.publication.id);
  assert.equal((await publications.page({ id: "alice" }, { kind: "home" })).items.length, 1);
  assert.equal((await publications.page({ id: "bob" }, { kind: "home" })).items.length, 0);
  await publications.setSocial({ id: "bob" }, agent.id, { following: true });
  assert.equal((await publications.page({ id: "bob" }, { kind: "home", tab: "following" })).items.length, 0);
  await assert.rejects(publications.get({ id: "bob", managedAgents: [agent.id] }, choice.seed), /introuvable/);
  await assert.rejects(publications.getEditable({ id: "alice" }, choice.seed), /introuvable/);
  await assert.rejects(publications.publish({ id: "alice" }, choice.seed, saved.publication.revision), /introuvable/);
  const row = db.prepare("SELECT path FROM publication WHERE id=?").get(choice.seed) as { path: string };
  const markdown = await readFile(join(root, row.path, "index.md"), "utf8");
  assert.match(markdown, /visibility: private/); assert.match(markdown, /test_content: true/);
  assert.ok(markdown.includes(agent.id)); assert.ok(markdown.includes(run.topicId));
  for (let n = 1; n <= 4; n++) {
    const page = await publications.conversation({ id: "alice" }, `${choice.seed}/${n}`);
    assert.deepEqual(page.thread.map(entry => entry.ref), [1, 2, 3, 4].map(i => `${choice.seed}/${i}`));
    assert.equal(page.parent.ref, `${choice.seed}/${n}`);
    assert.equal(page.ancestors.length, 0);
    assert.equal(page.children.length, 0);
    assert.ok(page.thread.every(entry => entry.replyCount === 0));
  }
  await assert.rejects(publications.conversation({ id: "bob" }, `${choice.seed}/1`), /introuvable/);
  const graph = createGraphRepository({ vault, db, publications });
  assert.ok((await graph.authorizedGraph({ id: "alice" })).publications.some(p => p.id === choice.seed));
  assert.ok(!(await graph.authorizedGraph({ id: "bob" })).publications.some(p => p.id === choice.seed));
  await graph.rebuild();
  assert.equal((await publications.get({ id: "alice" }, choice.seed)).messages.length, 4);
  const post = await call("alice", { ...choice, seed: randomUUID(), count: 1, action: "publish", confirmed: true });
  assert.equal(post.publication!.type, "post");
  assert.equal((await publications.page({ id: "alice" }, { kind: "home" })).items.length, 2);
  // Public edited content retains its test marker and the same graph/conversation pipeline.
  const publicChoice = { ...choice, seed: randomUUID(), count: 2, action: "publish", confirmed: true, visibility: "public", publicConfirmed: true, messages: ["# Atelier modifié\n\n**Texte libre de test.**", "---\nreply_to: forged/999\n---\nSuite modifiée"] };
  await assert.rejects(call("bob", publicChoice), /introuvable/);
  await assert.rejects(call("alice", { ...publicChoice, publicConfirmed: false }), /explicitement/);
  await assert.rejects(call("alice", { ...publicChoice, messages: [" ", "Suite"] }));
  await assert.rejects(call("alice", { ...publicChoice, messages: ["Un seul"] }), /nombre/);
  await assert.rejects(call("alice", { ...publicChoice, visibility: "followers" }));
  const publicResult = await call("alice", publicChoice);
  assert.equal(publicResult.publication!.visibility, "public");
  assert.equal(publicResult.publication!.authorId, agent.id);
  const publicRead = await publications.get({ id: "bob" }, publicChoice.seed);
  assert.equal(publicRead.messages[0].body, "**Contenu de test fictif — 1/2**\n\n" + publicChoice.messages[0]);
  assert.equal(publicRead.messages[1].replyTo, null); // user Markdown never injects conversation metadata
  assert.equal((await publications.conversation({ id: "bob" }, `${publicChoice.seed}/2`)).thread[0].ref, `${publicChoice.seed}/1`);
  assert.ok((await publications.page({ id: "bob" }, { kind: "home" })).items.some(p => p.id === publicChoice.seed));
  assert.ok((await graph.authorizedGraph({ id: "bob" })).publications.some(p => p.id === publicChoice.seed && p.generatorId === agent.id));
  const publicRow = db.prepare("SELECT path FROM publication WHERE id=?").get(publicChoice.seed) as { path: string };
  const publicIndex = await readFile(join(root, publicRow.path, "index.md"), "utf8");
  assert.match(publicIndex, /visibility: public/); assert.match(publicIndex, /test_content: true/);
  assert.ok(publicIndex.includes(run.topicId));
  await assert.rejects(call("alice", { ...publicChoice, visibility: "private" }), /déjà été utilisé/);
  await assert.rejects(call("alice", { ...publicChoice, messages: ["Autre texte", "Suite"] }), /déjà été utilisé/);
  const publicPost = await call("alice", { ...publicChoice, seed: randomUUID(), count: 1, messages: ["Publication de test modifiée"] });
  assert.equal(publicPost.publication!.type, "post");
  assert.equal((await publications.get({ id: "bob" }, publicPost.publication!.id)).visibility, "public");
  await graph.rebuild();
  const restarted = createPublicationStore({ vault, db });
  assert.equal((await restarted.get({ id: "bob" }, publicChoice.seed)).messages[1].body, publicRead.messages[1].body);
  assert.ok((await restarted.page({ id: "bob" }, { kind: "home" })).items.some(p => p.id === publicChoice.seed));
  // The store guards public visibility and ownership itself, independently of the route schema.
  const direct = { id: randomUUID(), summary: "Test", messages: ["Texte"], topicIds: [run.topicId] };
  await assert.rejects(publications.publishGenerated({ id: "alice" }, agent.id, { ...direct, visibility: "public" }), /Confirmation publique/);
  await assert.rejects(publications.publishGenerated({ id: "bob" }, agent.id, { ...direct, visibility: "public", publicConfirmed: true }), /introuvable/);
  await assert.rejects(publications.publishGenerated({ id: "alice" }, agent.id, { ...direct, authorId: "alice" }));
  // Every edited message file starts with its test label, even when the label was removed or altered.
  const altered = await call("alice", { ...publicChoice, seed: randomUUID(), count: 3, visibility: "private", publicConfirmed: false, messages: ["Sans marquage", "**Contenu de test fictif — 1/3**\n\nMauvais numéro", "**Contenu de test fictif — 3/3**\n\nDéjà marqué"] });
  const alteredRow = db.prepare("SELECT path FROM publication WHERE id=?").get(altered.publication!.id) as { path: string };
  const files = (await import("node:fs/promises")).readdir(join(root, alteredRow.path));
  const messageFiles = (await files).filter(file => file !== "index.md").sort();
  assert.equal(messageFiles.length, 3);
  for (const [i, file] of messageFiles.entries()) assert.ok((await readFile(join(root, alteredRow.path, file), "utf8")).startsWith(`**Contenu de test fictif — ${i + 1}/3**\n\n`), file);
  assert.equal(altered.publication!.messages[2].body, "**Contenu de test fictif — 3/3**\n\nDéjà marqué");
  const alteredIndex = await readFile(join(root, alteredRow.path, "index.md"), "utf8");
  for (const field of ["author_type: ai", `author_id: ${agent.id}`, `generator: ${agent.id}`, "status: published", "generated_by: manual-fixture-v1", "thread_continuation: true", "confirmed_by: alice"]) assert.ok(alteredIndex.includes(field), field);
  const embeds = messageFiles.map(file => alteredIndex.indexOf(`/${file.replace(/\.md$/, "")}]]`));
  assert.ok(embeds[0] > 0 && embeds[0] < embeds[1] && embeds[1] < embeds[2], alteredIndex);
  // Restart with an empty index: Markdown alone restores visibility, attribution and thread order.
  const freshDb = new Database(":memory:"); t.after(() => freshDb.close());
  const rebuilt = createPublicationStore({ vault, db: freshDb });
  assert.equal((await rebuilt.get({ id: "alice" }, choice.seed)).visibility, "private");
  await assert.rejects(rebuilt.get({ id: "bob" }, choice.seed), /introuvable/);
  await assert.rejects(rebuilt.conversation({ id: "bob" }, `${choice.seed}/2`), /introuvable/);
  const rebuiltPublic = await rebuilt.get({ id: "bob" }, publicChoice.seed);
  assert.equal(rebuiltPublic.visibility, "public"); assert.equal(rebuiltPublic.authorType, "ai"); assert.equal(rebuiltPublic.authorId, agent.id);
  assert.deepEqual(rebuiltPublic.messages.map(m => m.body), publicRead.messages.map(m => m.body));
  assert.deepEqual((await rebuilt.get({ id: "alice" }, choice.seed)).messages.map(m => m.body), preview.preview!.messages);
  for (let n = 1; n <= 4; n++) {
    const page = await rebuilt.conversation({ id: "alice" }, `${choice.seed}/${n}`);
    assert.deepEqual(page.thread.map(entry => entry.ref), Array.from({ length: 4 }, (_, i) => `${choice.seed}/${i + 1}`));
    assert.ok(page.thread.every(entry => entry.publication?.authorId === agent.id));
  }
  const bobFeed = (await rebuilt.page({ id: "bob" }, { kind: "home" })).items.map(p => p.id);
  assert.ok(bobFeed.includes(publicChoice.seed) && !bobFeed.includes(choice.seed) && !bobFeed.includes(altered.publication!.id));
  const freshGraph = createGraphRepository({ vault, db: freshDb, publications: rebuilt });
  const bobGraph = (await freshGraph.authorizedGraph({ id: "bob" })).publications.map(p => p.id);
  assert.ok(bobGraph.includes(publicChoice.seed) && !bobGraph.includes(choice.seed));
  // Current Markdown ownership, not a stale grant or client field, controls reading.
  const agentFile = join(root, "generators/politiks/index.md");
  const original = await readFile(agentFile, "utf8");
  const { writeFile } = await import("node:fs/promises");
  await writeFile(agentFile, original.replace("owner_id: alice", "owner_id: bob"));
  await assert.rejects(publications.get({ id: "alice" }, choice.seed), /introuvable/);
  assert.equal((await publications.get({ id: "bob" }, choice.seed)).authorId, agent.id);
});
