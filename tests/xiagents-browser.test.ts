import assert from "node:assert/strict";
import { test } from "node:test";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import Database from "better-sqlite3";
import { chromium, type Browser } from "playwright-core";
import { createTestServer } from "./helpers/next-server";

test("ΞAgents browser: creation, preview, confirmation, private agent feed and conversations", { timeout: 120_000 }, async t => {
  const app = await createTestServer();
  const resources: { browser?: Browser } = {};
  t.after(async () => { await resources.browser?.close(); await app.dispose(); });
  await app.migrate(); await app.start();
  const browser = resources.browser = await chromium.launch({ executablePath: process.env.XI_E2E_CHROME ?? "/usr/bin/google-chrome-stable", headless: true });
  const alice = await browser.newContext(); const bob = await browser.newContext(); const anon = await browser.newContext();
  const headers = { Origin: app.origin };
  for (const [context, name] of [[alice, "Alice"], [bob, "Bob"]] as const) assert.equal((await context.request.post(`${app.origin}/api/auth/sign-up/email`, { headers, data: { name, email: `${name}@xiagents.test`, password: "xiagents test password" } })).status(), 200);
  const topicRun = (await (await alice.request.post(`${app.origin}/api/topics/runs`, { headers, data: { intent: "Politiks fictif" } })).json()).run;
  await alice.request.post(`${app.origin}/api/topics/runs/${topicRun.id}`, { headers, data: { action: "resume" } });
  const topic = await (await alice.request.post(`${app.origin}/api/topics/runs/${topicRun.id}`, { headers, data: { action: "confirm", relationsConfirmed: true, draft: { tag: "politiks", name: "Politiks", description: "Un compte de test", scope: "Scénarios fictifs", parentId: null, relatedIds: [] } } })).json();
  assert.equal(topic.run.state, "completed");
  const page = await alice.newPage(); page.setDefaultTimeout(12_000);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${app.origin}/dashboard/accounts`);
  assert.equal(new URL(page.url()).pathname, "/dashboard/xiagents");
  await page.getByRole("button", { name: "Proposer un ΞAgent", exact: true }).click();
  await page.getByLabel("Nom du ΞAgent", { exact: true }).waitFor();
  await page.getByLabel("Je confirme le ΞAgent", { exact: false }).check();
  await page.getByRole("button", { name: "Confirmer la création", exact: true }).click();
  await page.getByText("État : ΞAgent créé", { exact: true }).waitFor();
  await page.getByRole("link", { name: "Gérer @politiks", exact: true }).click();
  await page.getByRole("heading", { name: "Générer une publication" }).waitFor();
  const agentId = new URL(page.url()).pathname.split("/").at(-1)!;
  const catalog = await (await alice.request.get(`${app.origin}/api/accounts`)).json();
  const revision = catalog.accounts.find((account: { id: string }) => account.id === agentId).editorial.revision;
  assert.equal((await (await bob.request.get(`${app.origin}/api/accounts`)).json()).accounts.length, 0);
  assert.equal((await bob.request.get(`${app.origin}/dashboard/xiagents/${agentId}`)).status(), 404);
  const endpoint = `${app.origin}/api/xiagents/${agentId}/publications`;
  const request = { action: "generate", seed: crypto.randomUUID(), count: 1, accountRevision: revision };
  assert.equal((await anon.request.post(endpoint, { headers, data: request })).status(), 401);
  assert.equal((await bob.request.post(endpoint, { headers, data: request })).status(), 404);
  assert.equal((await alice.request.post(endpoint, { headers: { Origin: "https://foreign.example" }, data: request })).status(), 403);
  assert.equal((await alice.request.post(endpoint, { headers, data: { ...request, action: "publish", confirmed: false } })).status(), 400);
  assert.equal((await alice.request.post(endpoint, { headers, data: { ...request, action: "publish", confirmed: true, visibility: "public" } })).status(), 400);
  const db = new Database(app.databasePath); t.after(() => db.close());
  const count = () => (db.prepare("SELECT count(*) AS n FROM publication WHERE author_id=?").get(agentId) as { n: number }).n;
  assert.equal(count(), 0);
  await page.getByRole("button", { name: "Générer", exact: true }).click();
  const preview = page.getByLabel("Aperçu avant publication");
  await preview.waitFor();
  const first = await preview.textContent();
  assert.equal(await preview.getByRole("button", { name: "Publier", exact: true }).isDisabled(), true);
  await page.getByRole("button", { name: "Régénérer", exact: true }).click();
  await page.waitForFunction(previous => document.querySelector('[aria-label="Aperçu avant publication"]')?.textContent !== previous, first);
  assert.equal(count(), 0);
  await page.getByLabel("Je confirme la publication privée", { exact: false }).check();
  await preview.getByRole("button", { name: "Publier", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Publication enregistrée" }).waitFor();
  assert.equal(count(), 1);
  await page.getByRole("combobox", { name: /^Format/ }).selectOption("thread");
  await page.getByLabel("Nombre de messages").selectOption("10");
  await page.getByRole("button", { name: "Générer", exact: true }).click();
  await preview.getByText("Message 10", { exact: true }).waitFor();
  assert.equal(await preview.locator("li").count(), 10);
  await page.getByLabel("Je confirme la publication privée", { exact: false }).check();
  await preview.getByRole("button", { name: "Publier", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Publication enregistrée" }).waitFor();
  assert.equal(count(), 2);
  const row = db.prepare("SELECT id, path FROM publication WHERE author_id=? AND type='thread'").get(agentId) as { id: string; path: string };
  const saved = await (await alice.request.get(`${app.origin}/api/publications/${row.id}`)).json();
  assert.equal(saved.publication.authorId, agentId); assert.equal(saved.publication.authorType, "ai");
  assert.equal(saved.publication.visibility, "private"); assert.equal(saved.publication.messages.length, 10);
  assert.equal(saved.authors[agentId].handle, "@politiks");
  const markdown = await readFile(join(app.vaultPath, row.path, "index.md"), "utf8");
  assert.match(markdown, /author_type: ai/); assert.match(markdown, /visibility: private/); assert.ok(markdown.includes(topic.run.topicId));
  assert.equal((await bob.request.get(`${app.origin}/api/publications/${row.id}`)).status(), 404);
  await page.goto(`${app.origin}/dashboard`);
  const cards = page.getByRole("article", { name: "Publication de Politiks", exact: true });
  await cards.first().waitFor(); assert.equal(await cards.count(), 2);
  assert.ok(await cards.first().locator("[data-bloub]").count() > 0);
  await page.goto(`${app.origin}/dashboard/publications/${row.id}`);
  await page.getByText("Contenu de test fictif — 10/10", { exact: true }).waitFor();
  const conversationLink = page.locator(`a[href="/dashboard/publications/${row.id}/conversation/1"]`).first();
  await conversationLink.click();
  await page.locator("#m-1").first().waitFor();
  await page.getByRole("list", { name: "Réponses chronologiques" }).getByText("Contenu de test fictif — 2/10", { exact: true }).waitFor();
  // Markdown editing, final preview with the enforced test label, explicit public confirmation.
  await page.goto(`${app.origin}/dashboard/xiagents/${agentId}`);
  await page.getByRole("combobox", { name: /^Format/ }).selectOption("post");
  await page.getByRole("combobox", { name: "Visibilité" }).selectOption("public");
  await page.getByRole("button", { name: "Générer", exact: true }).click();
  await preview.waitFor();
  const publicConfirm = page.getByLabel("Je confirme la publication publique", { exact: false });
  await publicConfirm.check();
  await page.getByLabel("Markdown du message 1").fill("## Titre édité\n\nTexte **modifié** dans l’éditeur.");
  assert.equal(await publicConfirm.isChecked(), false);
  const finalPreview = preview.locator("li .xi-markdown");
  await finalPreview.getByRole("heading", { name: "Titre édité" }).waitFor();
  assert.ok((await finalPreview.textContent())!.startsWith("Contenu de test fictif — 1/1"));
  const previewHtml = await finalPreview.innerHTML();
  await publicConfirm.check();
  await preview.getByRole("button", { name: "Publier", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Publication enregistrée" }).waitFor();
  const publicRow = db.prepare("SELECT id FROM publication WHERE author_id=? AND visibility='public'").get(agentId) as { id: string };
  const bobRead = await (await bob.request.get(`${app.origin}/api/publications/${publicRow.id}`)).json();
  assert.equal(bobRead.publication.messages[0].body, "**Contenu de test fictif — 1/1**\n\n## Titre édité\n\nTexte **modifié** dans l’éditeur.");
  assert.equal(bobRead.publication.authorId, agentId);
  const bobPage = await bob.newPage(); bobPage.setDefaultTimeout(12_000);
  bobPage.on("pageerror", error => errors.push(error.message));
  await bobPage.goto(`${app.origin}/dashboard/publications/${publicRow.id}`);
  const published = bobPage.locator(".xi-markdown").filter({ has: bobPage.getByRole("heading", { name: "Titre édité" }) });
  await published.waitFor();
  assert.equal(await published.innerHTML(), previewHtml);
  assert.equal((await bobPage.goto(`${app.origin}/dashboard/publications/${row.id}`))!.status(), 404);
  await bobPage.close();
  await page.goto(`${app.origin}/dashboard/xiagents/${agentId}`);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: "/tmp/xiagents-mobile.png", fullPage: true });
  await page.goto("about:blank");
  await app.stop(); await app.start();
  await page.goto(`${app.origin}/dashboard/xiagents/${agentId}`); await page.getByRole("heading", { name: "Historique des publications" }).waitFor();
  assert.equal(await page.getByRole("article", { name: "Publication de Politiks", exact: true }).count(), 3);
  assert.equal((await (await bob.request.get(`${app.origin}/api/publications/${publicRow.id}`)).json()).publication.visibility, "public");
  assert.equal((await bob.request.get(`${app.origin}/api/publications/${row.id}`)).status(), 404);
  assert.deepEqual(errors, []);
  await page.goto("about:blank");
});
